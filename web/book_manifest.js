/* ── کتاب‌های یک درس را با فصل‌های واقعی می‌سازد ── */
function bookList(sid){
  const man = (typeof BOOK_MANIFEST !== "undefined") ? BOOK_MANIFEST[sid] : null;
  if(!man) return [];
  const src = (typeof BOOK_DATA !== "undefined") ? BOOK_DATA[sid] : null;
  if(!src) return [];
  const byId = {};
  src.parts.forEach(p => p.chapters.forEach(c => { byId[c.id] = c; }));
  return man.map(b => {
    const parts = b.sections.map(sec => ({
      title: sec.title,
      chapters: sec.ids.map(id => byId[id]).filter(Boolean)
    })).filter(p => p.chapters.length);
    const flat = parts.reduce((a,p)=>a.concat(p.chapters), []);
    return {
      sid: sid, id: b.id, title: b.title, sub: b.sub, icon: b.icon, level: b.level,
      desc: b.desc, teacher: b.teacher, parts: parts, chapters: flat,
      minutes: flat.reduce((a,c)=>a+(c.minutes||0),0),
      count: flat.length
    };
  });
}
/* همه کتاب‌های همه درس‌ها (مسطح) */
function allBooks(){
  const out = [];
  Object.keys(BOOK_MANIFEST).forEach(sid => bookList(sid).forEach(b => out.push(b)));
  return out;
}
function findBook(bookId){
  const all = allBooks();
  return all.find(b => b.id === bookId) || null;
}
function bookChapterIds(bookId){
  const b = findBook(bookId);
  return b ? b.chapters.map(c => c.id) : [];
}
function bookTotalCount(){
  return allBooks().reduce((a,b)=>a+b.chapters.length,0);
}
