# ۴) بررسی کاراکترهای غیرفارسی/غیرلاتین مشکوک در همه فایل‌های کنکور
import re
bad_chars = re.compile(r'[\u0400-\u04FF\uAC00-\uD7AF\u4E00-\u9FFF]')
for fn in sorted(os.listdir(WEB)):
    if not fn.startswith('konkur_'):
        continue
    s = open(os.path.join(WEB, fn), encoding='utf-8').read()
    hits = bad_chars.findall(s)
    print(('✅' if not hits else '❌'), fn, 'کاراکتر مشکوک:', len(hits), set(hits) if hits else '')
