"""اصلاح غلط‌های تایپی در فایل‌های کنکور ۱۰ سال"""
import os
WEB = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'web')

def fix(fn, pairs):
    path = os.path.join(WEB, fn)
    s = open(path, encoding='utf-8').read()
    for a, b in pairs:
        if a not in s:
            print('  ⚠️ پیدا نشد در', fn, ':', a[:50])
            continue
        s = s.replace(a, b)
        print('  ✓ اصلاح در', fn)
    open(path, 'w', encoding='utf-8').write(s)

