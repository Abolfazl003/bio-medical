ALL_QUESTIONS_FLAT.extend(EXTRA_EXAM_QUESTIONS)


def build_exam(year, n=25):
    """یک آزمون n سوالی از دروس مختلف می‌سازد."""
    # حداقل پوشش از همه دروس
    pool = list(ALL_QUESTIONS_FLAT)
    random.shuffle(pool)
    selected = []
    seen_subj = set()
    # اول حداقل یکی از هر موضوع
    for subj in QUESTION_BANK.keys():
        for q in pool:
            if q["subject"] == subj and q not in selected:
                selected.append(q)
                break
    # تا n سوال پر می‌کنیم
    for q in pool:
        if len(selected) >= n:
            break
        if q not in selected:
            selected.append(q)
    random.shuffle(selected)
    return {
        "year": year,
        "title": f"آزمون کنکور کارشناسی ارشد مهندسی پزشکی — دوره {year}",
        "questions": selected[:n],
    }


